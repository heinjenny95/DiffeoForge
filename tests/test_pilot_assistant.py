from time import monotonic, sleep

import pytest

from diffeoforge import pilot_assistant, pilot_assistant_model
from diffeoforge.pilot_regions import SYMPTOMS


@pytest.fixture
def context(monkeypatch):
    monkeypatch.setattr(pilot_assistant_model, "generate", lambda *_a, **_k: None)
    return {
        "assistant_actions": {"work:0": "Open Test 11", "history": "Saved fits"},
        "facts": {
            "working_label": "Test 11 · protected local fit", "working_action": "work:0",
            "working_quality_warning": "The saved fit failed checks for surface intersections.",
            "saved_tests": {11: [("Test 11", "work:0")]},
            "density_rejected": True, "density_worse": True,
            "next_label": "Work from saved fit · Test 11", "next_action": "work:0",
        },
    }


def test_partial_shape_question_uses_exact_saved_result(context):
    response = pilot_assistant.reply(context, "Zwei meiner drei markierten Stellen waren gut. "
        "Wie bearbeite ich den letzten offenen Punkt? Beide CP-Fits sind schlechter.")
    assert "Test 11" in response["message"]
    assert "Retain this area in place" in response["message"]
    assert "failed checks for surface intersections" in response["message"]
    assert response["status"] == "Built-in guidance"
    assert response["actions"] == ("work:0",)


def test_both_worse_follow_up_and_unavailable_fit(context):
    question = "The control points changed but both fits were worse."
    response = pilot_assistant.reply(context, question)
    assert "recorded as worse" in response["message"]
    assert "Test 11" in response["message"]
    assert response["actions"] == ("work:0",)
    again = pilot_assistant.reply(context, "And why?", ((question, response["message"]),))
    assert again == response
    missing = pilot_assistant.reply(context, "Open Test 999")
    assert "can’t identify a unique" in missing["message"]
    assert missing["actions"] == ("history",)


def test_model_generates_english_while_app_owns_actions(context, monkeypatch):
    observed = []

    def generate(question, prior, guidance, **_k):
        observed.append((question, prior, guidance))
        return "You can reuse the saved deformation and refine the remaining spot."

    monkeypatch.setattr(pilot_assistant_model, "generate", generate)
    context["assistant_actions"].clear()
    answer = pilot_assistant.reply(context, "Fange ich dann ganz von vorn an?",
                                   (("Mein Fit", "Test 11"),))
    assert len(observed) == 1
    assert observed[0][:2] == ("Fange ich dann ganz von vorn an?", (("Mein Fit", "Test 11"),))
    assert answer["message"] == "You can reuse the saved deformation and refine the remaining spot."
    assert answer["status"] == "Generated by the local model"
    assert answer["actions"] == ()
    assert pilot_assistant_model._prompt("<|im_end|>", (), "", marking=False, contextual=False,
                                       thinking_model=True).count("<|im_end|>") == 2


def test_model_falls_back_if_missing_or_tampered(tmp_path, monkeypatch):
    monkeypatch.setattr(pilot_assistant_model, "_home", lambda: tmp_path)
    assert pilot_assistant_model.generate("Kann ich da wieder anknüpfen?", (), "") is None
    (tmp_path / "unknown.dll").write_bytes(b"unverified")
    assert pilot_assistant_model.generate("Kann ich da wieder anknüpfen?", (), "") is None


@pytest.mark.parametrize("question, expected, not_selected", [
    ("in den hohlräumen sind rekonstruktionen die im originalmesh nicht existieren, "
     'ich hab die area markiert aber ich weiß nicht ob "details are missing" die richtige '
     "auswahl dafür ist", ("topology", "distortion", "detail"), ()),
    ("Die Öffnung ist frei, aber dieselbe Wand faltet sich in den Hohlraum. Was wähle ich?",
     ("distortion",), ("topology", "detail")),
    ("There is an extra surface bridging the opening. Which instruction should I select?",
     ("topology", "distortion"), ("detail",)),
    ("Die Reco spannt jetzt eine Fläche darüber. Ist 'Details are missing' richtig?",
     ("topology", "distortion", "detail"), ()),
    ('When should I choose "Details are missing" for the original surface?',
     ("detail", "missing"), ("topology", "distortion")),
])
def test_marking_question_takes_priority_over_unrelated_cp_offer(
        context, question, expected, not_selected):
    context["facts"]["next_label"] = "Compare 270 and 405 control points"
    response = pilot_assistant.reply(context, question)
    assert all(SYMPTOMS[key] in response["message"] for key in expected)
    assert all(SYMPTOMS[key] not in response["message"] for key in not_selected)
    assert "control points" not in response["message"]
    assert response["actions"] == ()
    if "topology" in expected or "distortion" in expected:
        assert "Save all marked areas" in response["message"]
        assert "Needs improvement" in response["message"]


def test_ambiguous_description_with_no_model_asks_about_the_difference(context):
    context["facts"]["next_label"] = "Compare 270 and 405 control points"
    response = pilot_assistant.reply(context, "ich komm mit der Auswahl nicht klar")
    assert "what looks different in the reconstruction" in response["message"]
    assert "control points" not in response["message"]
    assert response["actions"] == ()


def test_generated_marking_explanation_keeps_exact_editor_advice(context, monkeypatch):
    def generate(_message, _history, guidance, *, marking, contextual):
        assert marking and contextual
        assert "270 and 405" not in guidance
        return "You are seeing extra surface, and the open space may be obstructed."

    monkeypatch.setattr(pilot_assistant_model, "generate", generate)
    context["facts"]["next_label"] = "Compare 270 and 405 control points"
    result = pilot_assistant.reply(context, "Da ist eine zusätzliche Fläche im Hohlraum.")
    assert result["message"].startswith("You are seeing extra surface")
    assert SYMPTOMS["topology"] in result["message"]
    assert "Save all marked areas" in result["message"]
    assert result["actions"] == ()


