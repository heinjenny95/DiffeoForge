"""Generate a local answer and keep pilot actions bound to the verified view."""

import re

_WORDS = {
    "failure": r"fehler|failed|failure|abbruch|abgebrochen|error|blockiert|blocked|guard",
    "keep": (r"zurück|behalt|bewahr|retain|go back|keep|vorherig|früher|anknüpf|"
             r"\b(?:two|zwei|2)\b.{0,45}(?:stellen|areas)|\b(?:letzte|remaining)\b.{0,24}"
             r"(?:stelle|punkt|area|spot)"),
    "controls": r"\bcp\b|kontrollpunkt|control.point|dichter|denser",
    "iterations": r"iteration|konverg|converg|\+\s*300|toleran|solver.{0,16}block",
    "alignment": r"ausricht|align|template|vorlage|landmark|\bgpa\b|rotier|verdreht|rotat",
    "review": r"feedback|freigab|suitable|needs improvement|review|bewert|geeignet|prüf",
    "compare": r"vergleich|compare|unterschied|schlechter|worse|besser|better",
    "atlas": r"atlas|common|joint|gemeinsam",
    "next": (r"weiter|nächste|next|jetzt|\bklick|\bclick|fortsetz|continue|"
             r"was.{0,18}(?:tun|machen)|what.{0,14}(?:do|try)"),
}


def _topic(message):
    if re.search(r"\b(?:test|trial)\s*#?\s*\d+\b", message) and re.search(
            r"öffn|open|wähl|choose|work|arbeiten|verwenden|\buse\b", message):
        return "keep"
    return next((topic for topic, pattern in _WORDS.items() if re.search(pattern, message)), None)


def reply(context, message, history=()):
    from diffeoforge.pilot_assistant_marks import advice
    from diffeoforge.pilot_assistant_model import generate

    question = message.casefold().strip()
    marking = advice(question)
    topic = _topic(question)
    if not marking and history and topic in {None, "next", "review"}:
        if re.search(r"\b(?:und|and|opening|öffnung|wall|wand|point|punkt)\b|markier|marked",
                     question):
            marking = advice(history[-1][0].casefold())
    if not marking and topic in {None, "next"} and len(question.split()) < 9:
        if re.search(r"\b(und|and|that|dieser|warum|why|wieso|it|sie|öffnung|opening|wand|wall)\b",
                     question):
            for prior, _ in reversed(history):
                if previous_topic := _topic(prior.casefold()):
                    topic = previous_topic
                    break
    baseline = ({"message": marking, "actions": ()} if marking
                else _pilot_reply(context, question, topic))
    if not context["facts"].get("running") and not baseline.get("verified"):
        text = generate(message, history, baseline["message"], marking=bool(marking),
                        contextual=bool(marking or topic))
        if text is not None:
            if marking:
                text += "\n\n" + baseline["message"]
            return {**baseline, "message": text, "status": "Generated by the local model"}
    return {**baseline, "status": "Built-in guidance"}


def _pilot_reply(context, question, topic):
    facts = context["facts"]

    def answer(body, *actions):
        offered = context["assistant_actions"]
        actions = (facts.get("next_action") if action == "next" else action for action in actions)
        actions = tuple(dict.fromkeys(a for a in actions if a in offered))
        return {"message": body, "actions": actions}

    next_label = facts.get("next_label")
    next_text = f"Choose “{next_label}” next." if next_label else ""
    if facts.get("next_action") == "choose_method" and topic in {
            None, "next", "compare", "keep", "review", "controls", "iterations"}:
        return dict(answer(facts["next_reason"] + " " + next_text, "next"), verified=True)
    if facts.get("guard_stop") and topic == "keep":
        label = context["assistant_actions"]["review"]
        named = re.search(r"\b(?:test|trial)\s*#?\s*(\d+)\b", question)
        if named and not re.search(rf"\btest\s+{int(named[1])}\b", label.casefold()):
            return dict(answer(f"The available inspection here is “{label}”."), verified=True)
        return dict(answer(f"Choose “{label}” to inspect the saved evidence.", "review"),
                    verified=True)
    if facts.get("guard_stop") and topic in {None, "failure", "next", "iterations",
                                             "review", "compare"}:
        reason = facts["next_reason"]
        if facts.get("next_action") != "review":
            reason = " ".join(filter(None, (facts["guard_stop"], reason)))
        return dict(answer(reason + " " + next_text, "next"), verified=True)
    if reason := facts.get("next_reason"):
        if topic in {None, "failure", "next", "iterations", "controls", "atlas", "alignment"}:
            body = " ".join(filter(None, (reason, facts.get("expected_result"), next_text)))
            return dict(answer(body, "next", "accepted"), verified=True)
    source = facts.get("working_label")
    working_action = facts.get("working_action")
    if topic == "keep":
        if named := re.search(r"\b(?:test|trial)\s*#?\s*(\d+)\b", question):
            matches = facts["saved_tests"].get(int(named[1]), ())
            if len(matches) != 1:
                return answer("I can’t identify a unique starting fit for that test here. "
                              "Open the saved-fit list.", "history")
            source, working_action = matches[0]
        instruction = ("Mark the good areas again if needed and set them to "
                       "‘Retain this area in place’. Keep the remaining area on ‘Improve’ "
                       "and save the starting fit. The pilot then checks whether a protected "
                       "local test can be prepared.")
        warning = facts.get("working_quality_warning")
        if warning and working_action == facts.get("working_action"):
            instruction += f" {warning}"
        if source and working_action:
            return answer(f"Open {source} as the starting fit. " + instruction, working_action)
        return answer("Choose the saved fit that preserves the good areas. " + instruction,
                      "history", "review")

    if topic == "controls":
        counts = facts.get("density_counts")
        if facts.get("density_rejected"):
            prefix = "Both control-point fits were recorded as worse. " if facts.get(
                "density_worse") else "Both control-point fits were marked unsuitable. "
            return answer(prefix + (next_text or "Open the earlier fit and check the remaining "
                "areas."), "next", working_action, "history" if not working_action else None)
        prefix = (f"This comparison tests {counts[0]} and {counts[1]} control points. "
                  if counts else "")
        return answer(prefix + "More control points allow finer local movements. Compare the "
                      "results from the same starting fit to see their effect. " + next_text,
                      "next")

    if topic == "iterations":
        prefix = ("The saved fit reached its iteration limit. Numerical convergence is "
                  "unconfirmed. " if facts.get("iteration_limit") else "")
        return answer(prefix + "More iterations can help when the same setup is still visibly "
                      "improving the remaining area. Check the latest reconstruction and the "
                      "marked areas first.", "review")

    if topic == "alignment":
        return answer("Compare the original mesh and starting template in their saved alignment. "
                      "Check where the affected structures sit on both shapes. If the pose is "
                      "wrong, return to ‘Data & engine’.", "inputs")

    if topic == "review":
        return answer("‘Save feedback’ records what changed relative to the starting fit. If an "
                      "important detail is missing, choose ‘Needs improvement’. ‘Suitable fit’ "
                      "approves this form.", "review")

    if topic == "atlas":
        progress = facts.get("coverage")
        count = (f"Shared settings checked on {progress[0]} of {progress[1]} forms. "
                 if progress else "")
        return answer(count + "Individual approval covers this form. The pilot then checks the "
                      "shared settings, the joint fit and time resolution.", "review")

    if topic == "compare":
        return answer("Compare the saved fits in the same view. Check the remaining gap and the "
                      "areas that already looked good.", "compare", working_action,
                      "history" if not working_action else None)

    if facts.get("running"):
        return answer("The pilot is computing. You can review the marked areas once it is ready.")
    if next_text and topic == "next":
        return dict(answer(" ".join(filter(None, (facts.get("next_status"), next_text))),
                           "next"), verified=True)
    return answer("Which area or decision do you mean? Describe what you see on the original "
                  "and what looks different in the reconstruction.")
